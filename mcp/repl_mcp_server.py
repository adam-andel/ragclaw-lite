class MCPHandler(BaseHTTPRequestHandler):
    """JSON-RPC 2.0 handler that dispatches to registered language executors."""

    def do_GET(self):
        if self.path == "/health":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(b'{"status":"ok"}')
            return

        # File download: GET /files/<path-under-allow-dir>  (depth-agnostic;
        # supports nested per-user dirs like user_u2005/<ws>/<file>)
        if self.path.startswith("/files/") and _allow_dir:
            rel = self.path[len("/files/"):].lstrip("/")
            if rel.endswith("/"):
                rel = rel.rstrip("/")
            parts = [p for p in rel.split("/") if p]
            if parts:
                target = os.path.realpath(os.path.join(_allow_dir, *parts))
                root = os.path.realpath(_allow_dir)
                if target == root or target.startswith(root + os.sep):
                    if os.path.isdir(target):
                        try:
                            files = [f for f in os.listdir(target)
                                    if os.path.isfile(os.path.join(target, f))]
                            self.send_response(200)
                            self.send_header("Content-Type", "application/json")
                            self.end_headers()
                            self.wfile.write(json.dumps({
                                "path": rel,
                                "files": [{"name": f, "url": f"/files/{rel}/{f}"}
                                         for f in sorted(files)]
                            }, ensure_ascii=False).encode())
                            return
                        except Exception:
                            pass
                    elif os.path.isfile(target):
                        self.send_response(200)
                        self.send_header("Content-Type", "application/octet-stream")
                        # RFC 5987: percent-encode so spaces / non-ASCII don't
                        # break the ASCII-only header; browsers use filename*.
                        _fname = os.path.basename(target)
                        self.send_header(
                            "Content-Disposition",
                            "attachment; filename=\"%s\"; filename*=UTF-8''%s"
                            % (quote(_fname, safe=""), quote(_fname, safe="")),
                        )
                        self.end_headers()
                        with open(target, "rb") as f:
                            self.wfile.write(f.read())
                        return
            self.send_error(404)
            return
            # Per-user workspace file manager (trusted internal API).
        if self.path.startswith("/workspace"):
            try:
                self._handle_workspace_get()
            except Exception as e:  # noqa: BLE001 - never drop the connection
                self._json_response(500, {"error": f"workspace error: {e}"})
            return
        self.send_error(404)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        if self.path == "/workspace/":
            try:
                self._handle_workspace_post(length)
            except Exception as e:  # noqa: BLE001 - never drop the connection
                self._json_response(500, {"error": f"workspace error: {e}"})
            return
        body = json.loads(self.rfile.read(length)) if length else {}
        method = body.get("method", "")
        req_id = body.get("id", 0)

        if method == "tools/list":
            result = {"tools": _build_tools()}
        elif method == "tools/call":
            params = body.get("params", {})
            tool_name = params.get("name", "")
            arguments = params.get("arguments", {})
            code = arguments.get("code", "")
            subdir = arguments.get("subdir")
            # Caller-supplied IANA timezone (e.g. Asia/Shanghai). Validated inside
            # execute()/_validate_tz(); invalid values are ignored (UTC default).
            caller_tz = arguments.get("timezone")

            # ── Identity: verify Backend-signed envelope (fail closed) ──
            auth = arguments.get("auth") or params.get("auth")
            auth_info, auth_reason = _verify_auth_ex(auth)
            user = auth_info["user"] if auth_info else None
            if _auth_required and user is None:
                logger.warning("auth_reject tool=%s reason=%s", tool_name, auth_reason)
                # Secret-related rejections get a dedicated code so the Backend
                # can re-push the secret and replay the call (self-heal after an
                # mcp-repl restart). Malformed envelopes keep the generic code —
                # re-pushing would be pointless there.
                if auth_reason in ("no_secret", "bad_sig"):
                    err = {"code": _AUTH_ERR_SECRET,
                           "message": "Authentication failed: REPL auth secret is missing or "
                                      "out of sync with the Backend",
                           "data": {"reason": auth_reason}}
                else:
                    err = {"code": _AUTH_ERR_GENERIC,
                           "message": "Authentication failed: missing or invalid signature "
                                      "(a Backend-signed auth envelope is required)",
                           "data": {"reason": auth_reason}}
                resp = {"jsonrpc": "2.0", "id": req_id, "error": err}
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps(resp, ensure_ascii=False).encode())
                return

            # Route to correct executor by tool name
            executor = _EXECUTORS.get(tool_name)
            if executor and code:
                uid = auth_info["uid"] if auth_info else None
                text, generated = executor(code, subdir=subdir, user=user, uid=uid, tz=caller_tz)
                result = {"content": [{"type": "text", "text": text}]}
                if generated:
                    result["structuredContent"] = {"files": generated}
            else:
                result = {"content": [{"type": "text", "text": f"Unknown tool: {tool_name}"}]}
        else:
            self.send_error(404)
            return

        resp = {"jsonrpc": "2.0", "id": req_id, "result": result}
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(json.dumps(resp, ensure_ascii=False).encode())

    def do_DELETE(self):
        """Internal-only endpoint to remove a user's sandbox base directory.

        Path:  /user/<uid>
        Auth:  caller must present the shared ``REPL_AUTH_SECRET`` in the
               ``X-Repl-Auth`` header (same secret the Backend uses to sign
               envelopes). This keeps directory cleanup on the Backend's
               user-deletion path strictly internal.
        """
        if self.path.startswith("/user/"):
            self._handle_delete_user_dir()
            return
        if self.path.startswith("/workspace/"):
            try:
                self._handle_workspace_delete()
            except Exception as e:  # noqa: BLE001 - never drop the connection
                self._json_response(500, {"error": f"workspace error: {e}"})
            return
        self.send_error(404)

    def _handle_delete_user_dir(self):
        # Directory cleanup is only meaningful when a writable sandbox dir exists.
        if not _allow_dir:
            self._json_response(403, {"error": "sandbox not configured"})
            return
        provided = self.headers.get("X-Repl-Auth", "")
        if not _hmac_module.compare_digest(provided, _REPL_AUTH_SECRET):
            self._json_response(403, {"error": "unauthorized"})
            return

        m = re.fullmatch(r"/user/(\d+)", self.path)
        if not m:
            self._json_response(400, {"error": "invalid uid"})
            return
        uid = int(m.group(1))
        if uid < 0 or uid > 2147483647:
            self._json_response(400, {"error": "invalid uid"})
            return

        target = os.path.realpath(os.path.join(_allow_dir, f"user_u{uid}"))
        root = os.path.realpath(_allow_dir)
        # Path-traversal guard: the resolved target must be strictly inside
        # _allow_dir (never equal to it, never outside it).
        if target != root and not target.startswith(root + os.sep):
            self._json_response(400, {"error": "invalid path"})
            return

        if os.path.isdir(target):
            try:
                shutil.rmtree(target)
            except OSError as e:
                self._json_response(500, {"error": f"rmtree failed: {e}"})
                return
            self._json_response(200, {"deleted": f"user_u{uid}"})
        else:
            # Idempotent: nothing to remove is not an error.
            self._json_response(200, {"deleted": None, "note": "no such dir"})

    def _json_response(self, code: int, obj: dict):
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(json.dumps(obj, ensure_ascii=False).encode())

    # ── Workspace API (per-user sandbox file manager) ──────────────────────
    # Trusted internal endpoints: caller must present the shared REPL_AUTH_SECRET
    # in ``X-Repl-Auth`` and the target uid in ``X-Repl-Uid``. Every path is
    # resolved strictly inside ``user_u<uid>`` (path-traversal guarded by
    # _ws_safe), mirroring the DELETE /user/<uid> internal-auth pattern.
    def _workspace_auth(self):
        """Return ``(uid, None)`` on success or ``(None, error_dict)``."""
        if _REPL_AUTH_SECRET is None:
            return (None, {"error": "auth not configured"})
        if not _allow_dir:
            return (None, {"error": "sandbox not configured"})
        provided = self.headers.get("X-Repl-Auth", "")
        if not _hmac_module.compare_digest(provided, _REPL_AUTH_SECRET):
            return (None, {"error": "unauthorized"})
        raw = self.headers.get("X-Repl-Uid", "")
        try:
            uid = int(raw)
        except (TypeError, ValueError):
            return (None, {"error": "invalid uid"})
        if uid < 0 or uid > 2147483647:
            return (None, {"error": "invalid uid"})
        return (uid, None)

    def _handle_workspace_get(self):
        uid, err = self._workspace_auth()
        if err:
            self._json_response(403, err)
            return
        parsed = urlparse(self.path)
        # Download: GET /workspace/<rel>  (rel may contain '/')
        if parsed.path not in ("/workspace", "/workspace/"):
            # self.path is the raw (percent-encoded) HTTP request target, so a
            # filename with spaces / non-ASCII arrives as %20 / %E6%... and must
            # be decoded before resolving — urlparse does NOT decode the path.
            rel = unquote(parsed.path[len("/workspace"):].lstrip("/"))
            root = _workspace_root(uid)
            target = _ws_safe(root, rel)
            if target is None or not os.path.isfile(target):
                self.send_error(404)
                return
            self.send_response(200)
            self.send_header("Content-Type", "application/octet-stream")
            # RFC 5987: percent-encode the filename so spaces / non-ASCII don't
            # break the (ASCII-only) HTTP header; browsers decode filename*.
            _fname = os.path.basename(target)
            self.send_header(
                "Content-Disposition",
                "attachment; filename=\"%s\"; filename*=UTF-8''%s"
                % (quote(_fname, safe=""), quote(_fname, safe="")),
            )
            self.send_header("Content-Length", str(os.path.getsize(target)))
            self.end_headers()
            with open(target, "rb") as f:
                while True:
                    chunk = f.read(65536)
                    if not chunk:
                        break
                    self.wfile.write(chunk)
            return
        # List: GET /workspace/?path=<rel>
        q = parse_qs(parsed.query)
        rel = (q.get("path", [""])[0] or "").strip("/")
        root = _workspace_root(uid)
        target = _ws_safe(root, rel)
        if target is None:
            self._json_response(400, {"error": "invalid path"})
            return
        if not os.path.isdir(target):
            self._json_response(404, {"error": "no such directory"})
            return
        search_term = (q.get("search", [""])[0] or "").strip()
        if search_term:
            # Recursive filename search: walk the subtree under `target` and
            # return every dir/file whose name contains the (case-insensitive)
            # term. Results are scoped to the requested path, not the whole
            # sandbox. Capped to avoid pathological response sizes.
            entries = []
            term_lower = search_term.lower()
            cap = 2000
            for dirpath, dirnames, filenames in os.walk(target):
                dirnames.sort()
                for name in sorted(dirnames) + sorted(filenames):
                    if term_lower not in name.lower():
                        continue
                    full = os.path.join(dirpath, name)
                    if not (os.path.isdir(full) or os.path.isfile(full)):
                        continue
                    is_dir = os.path.isdir(full)
                    rel_path = os.path.relpath(full, root)
                    entries.append({
                        "name": name,
                        "type": "dir" if is_dir else "file",
                        "rel_path": rel_path,
                        "size": None if is_dir else os.path.getsize(full),
                        "mtime": os.path.getmtime(full),
                        "download_url": f"/workspace/{rel_path}" if not is_dir else None,
                    })
                    if len(entries) >= cap:
                        break
                if len(entries) >= cap:
                    break
            self._json_response(200, {"path": rel, "entries": entries, "search": search_term, "truncated": len(entries) >= cap})
            return
        entries = []
        for name in sorted(os.listdir(target)):
            full = os.path.join(target, name)
            is_dir = os.path.isdir(full)
            rel_path = f"{rel}/{name}" if rel else name
            entries.append({
                "name": name,
                "type": "dir" if is_dir else "file",
                "rel_path": rel_path,
                "size": None if is_dir else os.path.getsize(full),
                "mtime": os.path.getmtime(full),
                "download_url": f"/workspace/{rel_path}" if not is_dir else None,
            })
        self._json_response(200, {"path": rel, "entries": entries})

    def _handle_workspace_post(self, length: int):
        uid, err = self._workspace_auth()
        if err:
            self._json_response(403, err)
            return
        body = json.loads(self.rfile.read(length)) if length else {}
        action = body.get("action")
        root = _workspace_root(uid)
        acct = {"uid": int(uid), "gid": int(uid), "name": f"u{int(uid)}"}

        def _validate_rel(rel):
            rel = (rel or "").strip("/")
            if not rel:
                return None
            for seg in rel.replace("\\", "/").split("/"):
                if not seg or seg in (".", ".."):
                    return None
            return rel

        def _chown(path):
            if os.name != 'nt':
                try:
                    # Mirror _ensure_dir_owned: root-owned (server can rewrite)
                    # but group-owned by the executor with group-write, so the
                    # user's own code can still read/modify uploaded files.
                    # Mode 660 (rw-rw----): 'other' is excluded. Cross-user
                    # isolation is already enforced by the 770 sandbox dir, and we
                    # keep files non-world-readable for good measure.
                    os.chown(path, 0, acct["gid"])
                    os.chmod(path, 0o660)
                except OSError:
                    pass

        if action == "mkdir":
            rel = _validate_rel(body.get("name", ""))
            if rel is None:
                self._json_response(400, {"error": "invalid name"})
                return
            target = _ws_safe(root, rel)
            if target is None:
                self._json_response(400, {"error": "invalid path"})
                return
            if os.path.exists(target):
                self._json_response(409, {"error": "already exists"})
                return
            _ensure_dir_owned(target, acct, 0o770)
            self._json_response(200, {"created": rel})
            return

        if action == "upload":
            rel = _validate_rel(body.get("name", ""))
            if rel is None:
                self._json_response(400, {"error": "invalid name"})
                return
            target = _ws_safe(root, rel)
            if target is None:
                self._json_response(400, {"error": "invalid path"})
                return
            try:
                data = base64.b64decode(body.get("content") or "")
            except Exception:
                self._json_response(400, {"error": "invalid base64 content"})
                return
            parent = os.path.dirname(target)
            _ensure_dir_owned(parent, acct, 0o770)
            try:
                with open(target, "wb") as f:
                    f.write(data)
            except PermissionError:
                # Target may already be owned by the executor account (created
                # by the user's own code). The server owns the parent dir, so it
                # can delete the file and re-create it, preserving writability.
                if os.path.exists(target):
                    try:
                        os.remove(target)
                    except OSError:
                        pass
                    with open(target, "wb") as f:
                        f.write(data)
                else:
                    raise
            _chown(target)
            self._json_response(200, {"written": rel, "size": len(data)})
            return

        if action == "rename":
            path = _validate_rel(body.get("path", ""))
            new_name = (body.get("new_name") or "").strip()
            if path is None or not new_name or "/" in new_name or "\\" in new_name \
                    or new_name in (".", ".."):
                self._json_response(400, {"error": "invalid path or name"})
                return
            src = _ws_safe(root, path)
            if src is None or not os.path.exists(src):
                self._json_response(404, {"error": "no such path"})
                return
            new_rel = f"{os.path.dirname(path)}/{new_name}" if os.path.dirname(path) \
                else new_name
            dst = _ws_safe(root, new_rel)
            if dst is None or os.path.exists(dst):
                self._json_response(409, {"error": "target exists or invalid"})
                return
            os.rename(src, dst)
            _chown(dst)
            self._json_response(200, {"renamed": new_rel})
            return

        if action == "move":
            # Move N files/dirs into a target directory.
            #   dest  : target directory rel path ("" = sandbox root)
            #   paths : list of source rel paths to move
            # All sources are validated up-front; if ANY check fails nothing is
            # moved (atomic-ish, satisfies the "cancel all moves" requirement).
            dest_raw = (body.get("dest") or "").strip("/")
            paths = body.get("paths")
            if not isinstance(paths, list) or not paths:
                self._json_response(400, {"error": "no paths to move"})
                return
            # Resolve & validate destination directory.
            if dest_raw:
                dest_rel = _validate_rel(dest_raw)
                if dest_rel is None:
                    self._json_response(400, {"error": "invalid destination"})
                    return
                dest_dir = _ws_safe(root, dest_rel)
            else:
                dest_rel = ""
                dest_dir = root
            if dest_dir is None or not os.path.isdir(dest_dir):
                self._json_response(400, {"error": "destination is not a directory"})
                return
            dest_real = os.path.realpath(dest_dir)

            moves = []  # (src, dst) pairs to perform after full validation
            for p in paths:
                rel = _validate_rel(p)
                if rel is None:
                    self._json_response(400, {"error": f"invalid path: {p}"})
                    return
                src = _ws_safe(root, rel)
                if src is None or not os.path.exists(src):
                    self._json_response(404, {"error": f"no such path: {p}"})
                    return
                name = os.path.basename(rel)
                new_rel = f"{dest_rel}/{name}" if dest_rel else name
                dst = _ws_safe(root, new_rel)
                if dst is None:
                    self._json_response(400, {"error": f"invalid target for: {p}"})
                    return
                src_real = os.path.realpath(src)
                # Reject moving a directory into itself or one of its own subdirs.
                if os.path.isdir(src) and (
                    dest_real == src_real
                    or dest_real.startswith(src_real + os.sep)
                ):
                    self._json_response(
                        400,
                        {"error": "cannot move a directory into itself or its subdirectory"},
                    )
                    return
                # Already inside the destination → skip (no-op), don't error.
                if os.path.realpath(os.path.dirname(src)) == dest_real:
                    continue
                if os.path.exists(dst):
                    self._json_response(409, {"error": f"target exists: {name}"})
                    return
                moves.append((src, dst))

            for src, dst in moves:
                os.rename(src, dst)
                # Files get file-style ownership (root:gid, 0o660); directories
                # must keep search/exec perms (0o770), like mkdir does.
                if os.path.isdir(dst):
                    _ensure_dir_owned(dst, acct, 0o770)
                else:
                    _chown(dst)
            self._json_response(200, {"moved": len(moves)})
            return

        self._json_response(400, {"error": f"unknown action: {action}"})

    def _handle_workspace_delete(self):
        uid, err = self._workspace_auth()
        if err:
            self._json_response(403, err)
            return
        # self.path is percent-encoded (spaces -> %20, non-ASCII -> %E6%...);
        # decode so filenames with special chars resolve correctly.
        rel = unquote(self.path[len("/workspace/"):].lstrip("/"))
        # Never allow deleting the user's whole sandbox root.
        if not rel:
            self._json_response(400, {"error": "cannot delete root"})
            return
        root = _workspace_root(uid)
        target = _ws_safe(root, rel)
        if target is None or not os.path.exists(target):
            self.send_error(404)
            return
        try:
            if os.path.isdir(target):
                shutil.rmtree(target)
            else:
                os.remove(target)
        except OSError as e:
            self._json_response(500, {"error": f"delete failed: {e}"})
            return
        self._json_response(200, {"deleted": rel or "."})

    def do_PUT(self):
        length = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(length)) if length else {}
        if self.path == "/policy":
            self._handle_policy_update(body)
            return
        if self.path == "/auth-secret":
            self._handle_auth_secret_update(body)
            return
        self.send_error(404)

    def _handle_policy_update(self, body: dict):
        """Hot-reload network policy (called by backend /api/config/sandbox-network)."""
        mode = body.get("mode")
        if mode not in ("deny", "allow", "allowlist"):
            self._json_response(400, {"error": "invalid mode, expected deny|allow|allowlist"})
            return
        domains = body.get("domains") or []
        methods = body.get("methods") or []
        if isinstance(domains, str):
            domains = [d.strip() for d in domains.split(",") if d.strip()]
        if isinstance(methods, str):
            methods = [m.strip().upper() for m in methods.split(",") if m.strip()]
        _set_network_policy(mode, domains, methods)
        logger.info("policy_updated mode=%s domains=%d", mode, len(domains))
        self._json_response(200, {"status": "ok", "policy": _build_policy()})

    def _handle_auth_secret_update(self, body: dict):
        """Hot-reload the REPL identity HMAC secret (called by backend /api/config/repl-auth).

        Internal-network-only endpoint (no host port mapping), mirroring
        /policy. Body: {"secret": "<str>"} — must be a
        non-empty string; auth + per-user UID isolation are always on, so an
        empty secret is rejected rather than disabling them.
        """
        secret = body.get("secret")
        if not isinstance(secret, str) or not secret:
            self._json_response(400, {"error": "secret must be a non-empty string"})
            return
        try:
            _set_auth_secret(secret)
        except ValueError as e:
            self._json_response(400, {"error": str(e)})
            return
        logger.info("auth_secret_updated (rotation)")
        self._json_response(200, {
            "status": "ok",
            "auth_enabled": True,
            "isolation_enabled": True,
        })

    def log_message(self, _fmt, *args):
        logger.info("http %s", args[0])


