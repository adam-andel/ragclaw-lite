# Shared execution helpers
# ═══════════════════════════════════════════════════════════
# Per-execution timezone (IANA) for the current tool call, validated and set by
# execute() from the caller-supplied "timezone" argument, then read by each
# language run_fn when building the child environment. None => container default.
#
# Stored on a *thread-local* (NOT a module global) on purpose: the server is
# threaded (ThreadingHTTPServer) and execute() blocks on the concurrency slot
# (_acquire_slot) after setting the TZ. With a module global, a concurrent
# request in another thread would clobber _exec_tz while this one waits, so the
# resumed execution would build its child env with the *wrong* timezone (often
# None -> UTC). A thread-local keeps each request's TZ isolated. execute() sets
# it at the top of every call, so even a reused thread can never read a stale
# value.
_thread_tz = threading.local()


def _set_exec_tz(tz: str | None) -> None:
    _thread_tz.value = tz


def _get_exec_tz() -> str | None:
    return getattr(_thread_tz, "value", None)


def _validate_tz(tz: str | None) -> str | None:
    """Return ``tz`` if it is a real IANA timezone name, else None.

    Validation guards against an attacker injecting a bogus/malicious TZ that
    could fall back to POSIX TZ syntax with arbitrary command-like content.
    We accept only names present under /usr/share/zoneinfo (e.g. Asia/Shanghai,
    America/New_York, UTC). Returns None when validation fails or zoneinfo data
    is unavailable, so the caller falls back to the container default.
    """
    if not tz or not isinstance(tz, str):
        return None
    # Reject anything that looks like POSIX TZ syntax or path traversal.
    if "/" not in tz and tz not in ("UTC", "GMT"):
        # Allow simple region-less names only if they literally exist; keep it
        # strict by requiring a slash (Area/Location) for everything else.
        if tz not in ("UTC", "GMT"):
            return None
    tz = tz.strip()
    if not tz or ".." in tz or tz.startswith("/") or "\x00" in tz:
        return None
    zpath = os.path.join("/usr/share/zoneinfo", tz)
    if os.path.isfile(zpath) or os.path.islink(zpath):
        return tz
    # Fallback to zoneinfo module if the filesystem path layout differs.
    try:
        from zoneinfo import ZoneInfo  # noqa: F401
        ZoneInfo(tz)
        return tz
    except Exception:
        return None


def _sanitize_env(tz: str | None = None) -> dict:
    """Copy environ, strip credential-like vars, set thread limits for Docker.

    When ``tz`` is a valid IANA timezone it is injected as ``TZ`` so that child
    processes (e.g. Python ``datetime.now()``) observe the *user's* local time
    rather than the container default (UTC). This keeps file timestamps etc.
    aligned with what the end user expects, without hardcoding any region.
    """
    env = os.environ.copy()
    # Inject the caller's timezone so local time inside the sandbox matches the
    # user's locale. TZ takes precedence over /etc/localtime in glibc, and only
    # a validated IANA name is accepted (falls back to container default).
    if tz:
        _tz = _validate_tz(tz)
        if _tz:
            env["TZ"] = _tz
    for k in list(env.keys()):
        if any(pat in k.upper() for pat in ("KEY", "TOKEN", "SECRET", "PASSWORD", "CREDENTIAL")):
            env.pop(k, None)
    # Limit BLAS/numpy threads to avoid pthread_create failures under RLIMIT_NPROC
    env["OPENBLAS_NUM_THREADS"] = "1"
    env["OMP_NUM_THREADS"] = "1"
    env["MKL_NUM_THREADS"] = "1"
    env["NUMEXPR_NUM_THREADS"] = "1"
    # Matplotlib config dir (read-only rootfs workaround)
    env["MPLCONFIGDIR"] = "/tmp/matplotlib"
    # Inject current network policy so the guard preamble can enforce it.
    env["REPL_NETWORK_POLICY"] = json.dumps(_build_policy(), ensure_ascii=False)

   # ── Approach B: force every child through the egress broker ───
    # All HTTP(S) clients (requests/urllib3/httpx sync+async, curl, wget...)
    # read HTTP_PROXY/HTTPS_PROXY, which closes the asyncio/httpx bypass.
    # Internal RAGClaw traffic (mcp-repl <-> backend) stays direct via NO_PROXY.
    # In deny mode no proxy is injected — the in-process guard already blocks
    # everything, and there is nothing legitimate to proxy.
    if _network_mode != "deny":
        proxy = f"http://{_EGRESS_HOST}:{_EGRESS_PORT}"
        env["HTTP_PROXY"] = proxy
        env["HTTPS_PROXY"] = proxy
        env["http_proxy"] = proxy
        env["https_proxy"] = proxy
        env["NO_PROXY"] = "localhost,127.0.0.1,mcp-repl,ragclaw-lite"
        env["no_proxy"] = "localhost,127.0.0.1,mcp-repl,ragclaw-lite"
    return env


def _acquire_slot(timeout: int = 5) -> bool:
    """Try to acquire a concurrency slot. Returns False if busy."""
    return _exec_semaphore.acquire(timeout=timeout)


def _make_workdir(subdir: str | None = None, acct=None) -> str:
    """Resolve a workdir for an execution call.

    The workdir is always confined to the caller's sandbox root
    ``_allow_dir/user_<name>/`` (``_ws_safe`` rejects traversal, so a caller
    can never escape their own directory).

    Behaviour:
      * ``subdir`` empty → the user's **root** directory
        (``user_<name>/``). This is the default "workspace" the user manages
        through the UI; REPL tool outputs land here and persist.
      * ``subdir`` set → a user-chosen **sub-directory** (nested paths
        like ``myproject/data`` are allowed). Invalid/traversing values fall
        back to the root instead of erroring.

    In all cases the directory is created and chowned to the account (mode 700)
    so one user's code can neither read nor be read by others' directories.
    """
    if acct is not None and _allow_dir:
        base = os.path.join(_allow_dir, "user_" + acct["name"])
        _ensure_dir_owned(base, acct, 0o770)
        if subdir:
            target = _ws_safe(base, subdir)
            if target is None:
                target = base  # fall back to root on any unsafe input
            _ensure_dir_owned(target, acct, 0o770)
            return target
        # No subdir → use the user's root directory directly.
        return base

    # Non-isolated fallback (no per-account chroot): still confine via _ws_safe.
    if _allow_dir:
        root = _allow_dir
        if subdir:
            target = _ws_safe(root, subdir)
            if target is None:
                target = root
        else:
            target = root
        os.makedirs(target, exist_ok=True)
        return target
    return tempfile.mkdtemp(prefix="repl_")


